param([Parameter(Mandatory)][string]$Image)
$ErrorActionPreference = 'Stop'
$suffix = [guid]::NewGuid().ToString('N')
$network = 'signal-forge-ddsclient-smoke-' + $suffix
$container = 'signal-forge-ddsclient-smoke-' + $suffix
$networkCreated = $false
$containerCreated = $false
try {
    & docker network create --internal --label "signal-forge.integration=$suffix" $network | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'Could not create isolated smoke network.' }
    $networkCreated = $true
    & docker run -d --name $container --label "signal-forge.integration=$suffix" --network $network -p '127.0.0.1::5226' $Image | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'Could not start smoke container.' }
    $containerCreated = $true
    $inspection = (& docker inspect $container | ConvertFrom-Json)[0]
    $bindings = @($inspection.NetworkSettings.Ports.'5226/tcp')
    $binding = $bindings | Where-Object { $_ -and $_.HostPort } | Select-Object -First 1
    if ($binding -and $binding.HostIp -ne '127.0.0.1') { throw 'Smoke port is not loopback-bound.' }
    $url = if ($binding) { "http://127.0.0.1:$($binding.HostPort)" } else { "http://${container}:5226" }
    function Get-SmokeResponse([string]$Path) {
        if ($binding) {
            $response = Invoke-WebRequest "$url$Path" -TimeoutSec 3
            return @{ Status = [int]$response.StatusCode; Body = $response.Content }
        }
        # Docker 29 may suppress host port publication for internal-only networks.
        # Keep the app internal; a one-shot bash TCP client needs no external image/download.
        $clientName = 'signal-forge-ddsclient-client-' + [guid]::NewGuid().ToString('N')
        $command = 'exec 3<>/dev/tcp/"$1"/5226; printf "GET %s HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n" "$2" >&3; cat <&3'
        $raw = (& docker run --rm --name $clientName --network $network --entrypoint /bin/bash $Image -c $command http-smoke $container $Path) -join "`n"
        if ($LASTEXITCODE -ne 0) { throw 'Internal HTTP client failed.' }
        if ($raw -notmatch '^HTTP/1\.[01] (\d{3})') { throw 'Internal client did not receive an HTTP response.' }
        return @{ Status = [int]$Matches[1]; Body = $raw }
    }
    $deadline = [DateTime]::UtcNow.AddSeconds(30)
    $ready = $false
    while ([DateTime]::UtcNow -lt $deadline) {
        try {
            $health = Get-SmokeResponse '/health'
            if ($health.Status -eq 200 -and $health.Body -match '"status":"connected"') { $ready = $true; break }
        } catch { Start-Sleep -Milliseconds 250 }
    }
    if (-not $ready) { throw 'App health did not become ready within 30 seconds.' }
    $page = Get-SmokeResponse '/'
    if ($page.Status -ne 200 -or $page.Body -notmatch 'Signal Forge') { throw 'Workbench page did not render.' }
    $css = Get-SmokeResponse '/css/app.css'
    if ($css.Status -ne 200) { throw 'Static app assets are missing.' }
    $access = if ($binding) { 'loopback-only host port' } else { 'internal peer, no host port exposed' }
    Write-Output "PASS: health, workbench HTML and static CSS on $url; $access, isolated internal network, fresh anonymous data volume."
} catch {
    if ($containerCreated) { & docker logs --tail 40 $container }
    throw
} finally {
    # Remove only resources whose exact names were generated by this invocation.
    if ($containerCreated) { & docker rm -f -v $container | Out-Null }
    if ($networkCreated) { & docker network rm $network | Out-Null }
}
